import {readFile, writeFile} from 'node:fs/promises';

const readText = name => readFile(new URL(name, import.meta.url), 'utf8')
  .then(text => text.replace(/\r\n/g, '\n'));
const dependencyFiles = [
  '../locker-troubleshooting/serial.js',
  '../locker-troubleshooting/layouts.js',
  './port-watch.js',
];
const [page, css, app, photo, ...dependencies] = await Promise.all([
  readText('index.html'),
  readText('style.css'),
  readText('app.js'),
  readFile(new URL('locker-usb-hub.png', import.meta.url)),
  ...dependencyFiles.map(readText),
]);

function replaceRequired(text, pattern, replacement) {
  if (!pattern.test(text)) throw new Error('The standalone build could not find ' + pattern);
  return text.replace(pattern, () => replacement);
}

const moduleUrls = new Map(dependencyFiles.map((file, index) => {
  const source = dependencies[index];
  if (/^\s*import\b/m.test(source)) throw new Error('Bundle the imports in ' + file + ' before embedding it.');
  return [file, 'data:text/javascript;base64,' + Buffer.from(source).toString('base64')];
}));
const bundledApp = app.replace(/^(import\s+.+?\s+from\s+)'([^']+)';$/gm, (_, declaration, specifier) => {
  const url = moduleUrls.get(specifier.split('?')[0]);
  if (!url) throw new Error('Add ' + specifier + ' to the standalone build.');
  return declaration + "'" + url + "';";
});
if (/^\s*import\b(?![^\n]*from 'data:)/m.test(bundledApp)) {
  throw new Error('The standalone app still contains a file import.');
}
if (/<\/script/i.test(bundledApp) || /<\/style/i.test(css)) {
  throw new Error('Escape inline closing tags before embedding the app.');
}

let standalone = replaceRequired(page, /\n {6}<nav\b[^>]*\bdata-hosted-only[^>]*>[\s\S]*?<\/nav>/, '');
standalone = replaceRequired(standalone, /<link rel="stylesheet" href="style\.css[^"]*">/, '<style>\n' + css + '</style>');
standalone = replaceRequired(standalone, /src="locker-usb-hub\.png"/, 'src="data:image/png;base64,' + photo.toString('base64') + '"');
standalone = replaceRequired(standalone, /<script type="module" src="app\.js[^"]*"><\/script>/, '<script type="module">\n' + bundledApp + '</script>');
standalone = replaceRequired(standalone, /<!doctype html>/, '<!doctype html>\n<!-- Generated by build-standalone.mjs. Edit the app source and regenerate this file. -->');
await writeFile(new URL('locker-connection-check.html', import.meta.url), standalone, 'utf8');
